import traceback

PROJECT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT))

from markdown_reader.app import Document, ReaderApplication, GLib, Gtk, WebKit
from gi.repository import Graphene

ACTUAL_README = Path(os.environ.get("MR_TEST_DOCUMENT", PROJECT / "README.md")).expanduser().resolve()
